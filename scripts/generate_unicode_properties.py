"""Regenerate the MoonBit XML regex tables from the pinned Unicode 16 UCD."""
import hashlib
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

CHECKSUMS = {
    "DerivedGeneralCategory.txt": "7676ab755a41ef82108460238569e60ad65c191ddafe61b36c6765ec1353f293",
    "PropertyValueAliases.txt": "440fd3e5460b9bfe31da67b6f923992e1989d31fe2ed91e091c4b8f8e2620bf9",
    "Blocks.txt": "f3907b395d410f1b97342292ca6bc83dd12eb4b205f2a0c48efdef99e517d7b0",
}


def records(path):
    source = path.read_bytes()
    if hashlib.sha256(source).hexdigest() != CHECKSUMS[path.name]:
        raise ValueError(f"Unexpected Unicode data checksum: {path.name}")
    for line in source.decode("utf-8").splitlines():
        payload = line.split("#", 1)[0].strip()
        if payload:
            yield [part.strip() for part in payload.split(";")]


def name_key(name):
    return re.sub(r"[ _-]", "", name.lower())


source_dir = Path(sys.argv[1])
categories = defaultdict(list)
for interval, category in records(source_dir / "DerivedGeneralCategory.txt"):
    categories[category].append(interval.replace("..", "-"))
blocks = {name_key(name): interval.replace("..", "-") for interval, name in records(source_dir / "Blocks.txt")}
for kind, *aliases in records(source_dir / "PropertyValueAliases.txt"):
    if kind != "blk":
        continue
    known = next((blocks[name_key(alias)] for alias in aliases if name_key(alias) in blocks), None)
    if known is not None:
        blocks.update({name_key(alias): known for alias in aliases})

root = Path(__file__).resolve().parents[1]
with (root / "src/core/unicode_properties.mbt").open("w", encoding="utf-8") as output:
    for variable, values in (
        ("unicode_categories", {category: " ".join(intervals) for category, intervals in categories.items()}),
        ("unicode_blocks", blocks),
    ):
        print('///|\n// Unicode Character Database 16.0.0, generated by scripts/generate_unicode_properties.py.\n// See third_party/unicode/LICENSE for copyright and license.', file=output)
        print(f"let {variable} : Map[String, String] = Map([", file=output)
        for name, value in sorted(values.items()):
            print(f"  ({json.dumps(name)}, {json.dumps(value)}),", file=output)
        print("])\n", file=output)
